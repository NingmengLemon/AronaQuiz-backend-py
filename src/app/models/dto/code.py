from enum import IntEnum


class BusinessCode(IntEnum):
    """业务状态码枚举

    格式: {HTTP状态码}{业务状态编号}
    """

    # 成功状态码 (200xxx)
    SUCCESS = 200000
    CREATED = 200001
    UPDATED = 200002
    DELETED = 200003

    # 通用客户端错误状态码
    BAD_REQUEST = 400000
    UNAUTHORIZED = 401000
    FORBIDDEN = 403000
    NOT_FOUND = 404000
    CONFLICT = 409000
    VALIDATION_ERROR = 400001

    # 用户相关状态码
    USER_NOT_FOUND = 404001
    USER_ALREADY_EXISTS = 409001
    USERNAME_INVALID = 400002
    EMAIL_INVALID = 400003
    NICKNAME_INVALID = 400004
    EMAIL_ALREADY_EXISTS = 409002
    USERNAME_ALREADY_EXISTS = 409003
    NICKNAME_ALREADY_EXISTS = 409004

    # 题目相关状态码
    PROBLEM_NOT_FOUND = 404002
    PROBLEMSET_NOT_FOUND = 404003
    PROBLEM_ALREADY_EXISTS = 409005
    PROBLEMSET_ALREADY_EXISTS = 409006

    # 会话相关状态码
    SESSION_EXPIRED = 401001
    SESSION_INVALID = 401002
    ALREADY_LOGGED_IN = 409007
    LOGIN_FAILED = 401003
    LOGOUT_FAILED = 400004
    TOKEN_REFRESH_FAILED = 401004

    # 系统内部错误
    INTERNAL_ERROR = 500000
    DATABASE_ERROR = 500001
    UNKNOWN_ERROR = 500002

    # 限流错误
    TOO_MANY_REQUESTS = 429000
